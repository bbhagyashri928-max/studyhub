#include <stdio.h>

int main() {
    int num1 = 25;
    int num2 = 17;
    int sum = num1 + num2;

    printf("Number 1: %d\\n", num1);
    printf("Number 2: %d\\n", num2);
    printf("Sum = %d + %d = %d\\n", num1, num2, sum);
    return 0;
}
